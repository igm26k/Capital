import { test, expect } from '@playwright/test';

test('budgets, reports and explicit rule preview preserve exact amounts and replay settings', async ({ page, context }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Создать профиль', exact: true }).click();
  await page.getByLabel('Электронная почта').fill(`analytics-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Пароль', { exact: true }).fill('synthetic-browser-password-2026');
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Выйти', exact: true })).toBeVisible();
  await page.getByLabel('Название счета').fill('Analytics cash');
  await page.getByLabel('Начальный остаток, EUR').fill('100,00');
  await page.getByRole('button', { name: 'Создать счет', exact: true }).click();
  await expect(page.locator('.accounts strong')).toHaveText('100,00 EUR');
  await page.getByLabel('Название категории', { exact: true }).fill('Analytics food');
  await page.getByRole('button', { name: 'Создать категорию', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Изменить категорию Analytics food', exact: true })).toBeVisible();
  await page.getByLabel('Сумма', { exact: true }).fill('8,00');
  await page.getByLabel('Категория', { exact: true }).selectOption({ label: 'Analytics food' });
  await page.getByLabel('Примечание', { exact: true }).fill('Classified purchase');
  await page.getByRole('button', { name: 'Сохранить операцию', exact: true }).click();
  await expect(page.locator('.accounts strong')).toHaveText('92,00 EUR');
  await page.getByLabel('Сумма', { exact: true }).fill('2,00');
  await page.getByLabel('Получатель', { exact: true }).fill('Test shop');
  await page.getByRole('button', { name: 'Сохранить операцию', exact: true }).click();
  await expect(page.locator('.accounts strong')).toHaveText('90,00 EUR');
  await page.getByText('Бюджеты, отчеты и правила', { exact: true }).click();
  const panel = page.getByRole('region', { name: 'Бюджеты и отчеты', exact: true });
  await expect(panel.getByText('Расходы за вычетом возвратов: 10,00 EUR', { exact: true })).toBeVisible();
  await panel.getByLabel('Название бюджета').fill('Food monthly');
  await panel.getByLabel('Категория бюджета').selectOption({ label: 'Analytics food' });
  await panel.getByLabel('Лимит бюджета').fill('10,00');
  const commands: { key: string | undefined; body: string | null }[] = [];
  let dropped = false;
  await page.route('**/api/v1/workspaces/*/budgets', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    commands.push({ key: route.request().headers()['idempotency-key'], body: route.request().postData() });
    const response = await route.fetch(); expect(response.status()).toBe(201);
    if (!dropped) { dropped = true; await route.abort('connectionfailed'); } else await route.fulfill({ response });
  });
  await panel.getByRole('button', { name: 'Сохранить бюджет', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Повторить запрос настроек', exact: true })).toBeVisible();
  await page.reload();
  await page.getByText('Бюджеты, отчеты и правила', { exact: true }).click();
  await panel.getByRole('button', { name: 'Повторить запрос настроек', exact: true }).click();
  await expect(panel.getByText('Близко к лимиту', { exact: false })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Повторить запрос настроек', exact: true })).toHaveCount(0);
  await expect.poll(() => commands.length).toBe(2); expect(commands[1]).toEqual(commands[0]);
  await panel.getByLabel('Название правила').fill('Shop rule');
  await panel.getByLabel('Категория правила').selectOption({ label: 'Analytics food' });
  await panel.getByLabel('Получатель содержит').fill('test shop');
  await panel.getByRole('button', { name: 'Сохранить правило', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Изменить правило Shop rule', exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Предпросмотр правил за период', exact: true }).click();
  await panel.getByRole('button', { name: 'Проверить применение пакета 1', exact: true }).click();
  await panel.getByRole('button', { name: 'Подтвердить применение правил', exact: true }).click();
  await expect(panel.getByText('Лимит достигнут или превышен', { exact: false })).toBeVisible();
  await page.getByLabel('Сумма', { exact: true }).fill('3,00');
  await page.getByLabel('Получатель', { exact: true }).fill('Test shop');
  await page.getByLabel('Примечание', { exact: true }).fill('Automatic category');
  await page.getByRole('button', { name: 'Сохранить операцию', exact: true }).click();
  await expect(panel.getByText('Расходы за вычетом возвратов: 13,00 EUR', { exact: true })).toBeVisible();
  await expect(page.locator('.history > li').filter({ hasText: 'Automatic category' })).toContainText('Analytics food · 3,00 EUR');
  await panel.getByRole('button', { name: 'Показать исходные операции отчета', exact: true }).click();
  await expect(page.locator('.history > li')).toHaveCount(4);
  const auth = await (await context.request.get('/api/v1/auth/session')).json();
  const root = `/api/v1/workspaces/${auth.workspace.id}`;
  const budgets = await (await context.request.get(`${root}/budgets`)).json();
  expect(budgets.items).toHaveLength(1); expect(budgets.items[0].spent_minor).toBe('1300');
  expect(budgets.items[0].remaining_minor).toBe('-300');
  page.once('dialog', dialog => dialog.accept());
  await panel.getByRole('button', { name: 'Удалить бюджет Food monthly', exact: true }).click();
  await expect(panel.getByText('Бюджетов пока нет.', { exact: true })).toBeVisible();
});
