#!/usr/bin/env python3
"""Generate Android API DTOs from the shared OpenAPI; --check prevents drift."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
schemas = json.loads((root / 'contracts/openapi.json').read_text())['components']['schemas']
names = ['EmailChallenge', 'PasswordChanged', 'RegistrationConfirm', 'RecoveryRequest', 'RecoveryConfirm', 'Profile', 'Workspace', 'Session', 'BearerAuth', 'Login', 'Register', 'Acknowledgement', 'SessionList', 'Account', 'AccountCreate', 'AccountUpdate', 'AccountList', 'MutationResult', 'Transaction', 'Category', 'Tag', 'Tombstone', 'Rate', 'Entry', 'Allocation', 'AllocationInput', 'ExpenseCreate', 'IncomeCreate', 'TransactionList', 'ExpenseReplace', 'IncomeReplace', 'TransactionDelete', 'VersionExpectation', 'CategoryList', 'TagList', 'CategoryCreate', 'TagCreate', 'CategoryUpdate', 'TagUpdate', 'TransferCreate', 'FeeInput', 'TransferReplace', 'RefundCreate', 'RefundAllocationInput', 'RefundReplace', 'AdjustmentCreate', 'AdjustmentReplace', 'BulkItem', 'BulkClassification', 'SnapshotCreate', 'Snapshot', 'SnapshotItem', 'SnapshotPage', 'WorkspaceChange', 'SyncGroup', 'SyncChanges', 'ReceiptEntity', 'FieldError', 'ConflictVersion', 'Error', 'ActionOutcome', 'Report', 'ReportTotals', 'ReportCategory', 'ReportBalance', 'ReportDailyBalance', 'Budget', 'BudgetCreate', 'BudgetUpdate', 'BudgetView', 'BudgetList', 'PlanningDeleted', 'PlanningDelete', 'Rule', 'RuleCreate', 'RuleUpdate', 'RuleList', 'RulePreview', 'ImportMapping', 'ImportCreate', 'ImportRow', 'ImportPreview', 'ImportProgress', 'ImportConfirm', 'ImportDecision', 'ExportResult', 'SourceEventCreate', 'SourceEvent', 'SourceEventList']
def kotlin_type(schema):
    if schema.get('oneOf') == [{'$ref': '#/components/schemas/MutationResult'}, {'$ref': '#/components/schemas/Error'}]:
        return 'ActionResponse'
    if isinstance(schema.get('type'), list):
        values = [value for value in schema['type'] if value != 'null']
        assert len(values) == 1 and 'null' in schema['type']
        return kotlin_type({**schema, 'type': values[0]}) + '?'
    if 'allOf' in schema:
        refs = [x for x in schema['allOf'] if '$ref' in x]
        assert len(refs) == 1
        return kotlin_type(refs[0])
    if 'anyOf' in schema:
        values = [x for x in schema['anyOf'] if x.get('type') != 'null']
        assert len(values) == 1
        return kotlin_type(values[0]) + '?'
    if schema.get('type') == 'array':
        return 'List<' + kotlin_type(schema['items']) + '>'
    if '$ref' in schema:
        name = schema['$ref'].split('/')[-1]
        return name if name in names else kotlin_type(schemas[name])
    if 'const' in schema:
        return 'Boolean' if isinstance(schema['const'], bool) else 'Int' if isinstance(schema['const'], int) else 'String'
    return {'string': 'String', 'boolean': 'Boolean', 'integer': 'Int'}[schema['type']]
lines = ['// Generated by scripts/generate-android-contracts.py. Do not edit.',
         'package com.capital.accounting.api', '', 'import kotlinx.serialization.*', 'import kotlinx.serialization.json.*', '']
lines += ['@Serializable(with = ActionResponseSerializer::class)', 'sealed interface ActionResponse', '',
          'object ActionResponseSerializer : JsonContentPolymorphicSerializer<ActionResponse>(ActionResponse::class) {',
          '    override fun selectDeserializer(element: JsonElement): DeserializationStrategy<ActionResponse> =',
          '        when {',
          '            "action_id" in element.jsonObject -> MutationResult.serializer()',
          '            "code" in element.jsonObject -> Error.serializer()',
          '            else -> throw SerializationException("Invalid action response")',
          '        }', '}', '']
models = []
for name in names:
    schema = schemas[name]
    if 'oneOf' not in schema:
        models.append((name, schema, None))
        continue
    variants = schema['oneOf']
    assert all(v['properties']['entity_type'].get('const') for v in variants)
    common = {field: value for field, value in variants[0]['properties'].items()
              if field != 'data' and all(field in variant['properties'] for variant in variants)}
    common_fields = {field: kotlin_type(value) for field, value in common.items()}
    operation = 'operation' in common
    selection = 'element.jsonObject["entity_type"]?.jsonPrimitive?.content'
    if operation:
        selection = '(' + selection + ') + ":" + (element.jsonObject["operation"]?.jsonPrimitive?.content)'
    lines += [f'@Serializable(with = {name}Serializer::class)', f'sealed interface {name} {{']
    lines += [f'    val {field}: {value}' for field, value in common_fields.items()]
    lines += ['}', '', f'object {name}Serializer : JsonContentPolymorphicSerializer<{name}>({name}::class) {{',
              f'    override fun selectDeserializer(element: JsonElement): DeserializationStrategy<{name}> =',
              f'        when ({selection}) {{']
    for variant in variants:
        entity = variant['properties']['entity_type']['const']
        op = variant['properties']['operation']['const'] if operation else ''
        variant_name = name + entity.title() + op.title()
        discriminator = entity + (':' + op if operation else '')
        lines += [f'            "{discriminator}" -> {variant_name}.serializer()']
        models.append((variant_name, variant, (name, common_fields)))
    lines += [f'            else -> throw SerializationException("Invalid {name} type")', '        }', '}', '']
for name, schema, parent in models:
    assert set(schema['required']) == set(schema['properties'])
    lines += ['@Serializable', f'data class {name}(']
    lines += [f'    {"override " if parent and field in parent[1] else ""}val {field}: {kotlin_type(value)},' for field, value in schema['properties'].items()]
    lines += [(') : ' + parent[0] + ' {') if parent else ') : ActionResponse {' if name in ('MutationResult', 'Error') else ') {']
    checks = []
    for field, value in schema['properties'].items():
        if 'const' in value:
            checks.append(f'        require({field} == {json.dumps(value["const"])}) {{ "Invalid {name}.{field}" }}')
        if 'allOf' in value:
            for constraint in value['allOf']:
                for key, prop in constraint.get('properties', {}).items():
                    if 'const' in prop:
                        checks.append(f'        require({field}.{key} == {json.dumps(prop["const"])}) {{ "Invalid {name}.{field}.{key}" }}')
        if 'enum' in value:
            values = ', '.join(json.dumps(x) for x in value['enum'])
            checks.append(f'        require({field} in setOf({values})) {{ "Invalid {name}.{field}" }}')
    if checks: lines += ['    init {'] + checks + ['    }']
    lines += [f'    override fun toString() = "{name}([redacted])"', '}', '']
content = '\n'.join(lines)
path = root / 'android/app/src/main/java/com/capital/accounting/api/ApiModels.kt'
if '--check' in sys.argv:
    assert path.read_text() == content, 'Android DTOs differ from OpenAPI; regenerate'
    print('PASS Android API DTOs match shared OpenAPI')
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
